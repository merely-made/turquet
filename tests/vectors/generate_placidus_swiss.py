"""Maintainer-only independent oracle; run with the natal-houses oracle-env Python.

This deliberately does not run generate-oracle.py: that script overwrites the
existing Equal/WholeSign fixtures and tests. Only Placidus-specific data is written.
"""
import json
import math
from pathlib import Path

import swisseph as swe


def generate():
    rows = []
    unavailable = []
    cases = [
        (2000, 1, 1, 12, 40.7128, -74.006),
        (2024, 6, 21, 0, -33.8688, 151.2093),
        (2024, 12, 21, 18, 51.4779, 0),
        (1985, 4, 12, 6, -34.6, -58.38),
        (2024, 3, 20, 0, 60, 179.99),
        (2024, 3, 20, 12, -60, -179.99),
        # Swiss documentation's demanding near-polar example (section 6.7).
        (2000, 1, 26, 8 + 8 / 60, 66.562, 30),
    ]
    # Both hemispheres, all sidereal quadrants, solstices, equinoxes, equator,
    # longitude wraps and near-polar geometry. No Turquet output is used.
    for month, day in [(3, 20), (6, 21), (12, 21)]:
        for lat in [-66.55, -60, -30, 0, 30, 60, 66.55]:
            for hour in range(0, 24, 2):
                cases.append((2024, month, day, hour, lat, 179.99 if hour % 4 else -179.99))
    for lat in [-90, -80, -66.57, 66.57, 80, 90]:
        for hour in [0, 6, 12, 18]:
            cases.append((2024, 6, 21, hour, lat, 0))
    for year, month, day, hour, lat, lon in cases:
        jd = swe.julday(year, month, day, hour)
        row = dict(tt_jd=jd + swe.deltat(jd), ut1_jd=jd, latitude=lat, longitude=lon)
        try:
            cusps, points = swe.houses_ex(jd, lat, lon, b"P", 0)
        except swe.Error as error:
            # pyswisseph raises on Swiss ERR; never record fallback cusps.
            unavailable.append(dict(row, error=str(error)))
        else:
            rows.append(dict(row, ascendant=points[0], midheaven=points[1], cusps=cusps))
    target = Path(__file__).resolve().parent
    observed = []
    for lat, lon, xp, yp in [
        (40.7128, -74.006, 2.47230737e-7, 1.82640464e-6),
        (-33.8688, 151.2093, -1.2e-6, 0.8e-6),
        (40.7128, -74.006, 0.02, -0.03),
        (-60, 179.99, -0.04, 0.01),
        (45, 37, 0.02, 0),
        (-45, -120, 0, -0.03),
    ]:
        jd = swe.julday(2024, 6, 21, 0)
        tt = jd + swe.deltat(jd)
        phi, lam = math.radians(lat), math.radians(lon)
        x, y, z = math.cos(phi) * math.cos(lam), math.cos(phi) * math.sin(lam), math.sin(phi)
        # Independent scalar inverse of SOFA W=Rx(-yp) Ry(-xp) Rz(sp),
        # using passive coordinate rotations and the ITRS geodetic normal.
        # SOFA sp00: -47 microarcsec per Julian century since J2000.
        sp = math.radians(-47e-6 / 3600 * ((tt - 2451545.0) / 36525))
        y, z = math.cos(yp) * y + math.sin(yp) * z, -math.sin(yp) * y + math.cos(yp) * z
        x, z = math.cos(xp) * x - math.sin(xp) * z, math.sin(xp) * x + math.cos(xp) * z
        x, y = math.cos(sp) * x - math.sin(sp) * y, math.sin(sp) * x + math.cos(sp) * y
        corrected_lat = math.degrees(math.atan2(z, math.hypot(x, y)))
        corrected_lon = math.degrees(math.atan2(y, x))
        cusps, points = swe.houses_ex(jd, corrected_lat, corrected_lon, b"P", 0)
        observed.append(dict(tt_jd=tt, ut1_jd=jd, latitude=lat, longitude=lon,
                             xp_radians=xp, yp_radians=yp, zenith_tirs=[x, y, z],
                             corrected_latitude=corrected_lat, corrected_longitude=corrected_lon,
                             ascendant=points[0], midheaven=points[1], cusps=cusps))
    data = dict(
        authority="Swiss Ephemeris " + swe.version + " through pyswisseph " + str(swe.__version__),
        source="https://www.astro.com/swisseph/swisseph.htm",
        interface="https://www.astro.com/swisseph/swephprg.htm",
        generator="generate_placidus_swiss.py; houses_ex(UT1, latitude, longitude, b'P', 0); TT=UT1+deltat(UT1)",
        scope="Independent tropical geometry data only; no Swiss source or runtime distributed. ERR cases discard fallback cusps.",
        tolerance_degrees=0.002,
        rows=rows,
        unavailable=unavailable,
        observed_reference="Python math scalar Rz(-sp) Ry(xp) Rx(yp) applied to ITRS geodetic normal; Swiss P at resulting coordinates",
        observed=observed,
    )
    (target / "placidus_swiss.json").write_text(json.dumps(data, indent=2) + "\n")
    # Compile-ready mirror avoids a JSON dependency in the Rust test lane.
    def values(row):
        return ", ".join(repr(float(row[k])) for k in ["tt_jd", "ut1_jd", "latitude", "longitude"])
    rust = "// Generated by generate_placidus_swiss.py; independent Swiss data.\n"
    rust += "const PLACIDUS_SWISS: &[(f64, f64, f64, f64, f64, f64, [f64; 12])] = &[\n"
    for row in rows:
        rust += "    (" + values(row) + ", " + repr(row["ascendant"]) + ", " + repr(row["midheaven"]) + ", " + repr(list(row["cusps"])) + "),\n"
    rust += "];\nconst PLACIDUS_UNAVAILABLE: &[(f64, f64, f64, f64)] = &[\n"
    for row in unavailable:
        rust += "    (" + values(row) + "),\n"
    rust += "];\nconst PLACIDUS_OBSERVED: &[(f64, f64, f64, f64, f64, f64, f64, f64, f64, f64, [f64; 12])] = &[\n"
    for row in observed:
        rust += "    (" + values(row) + ", " + ", ".join(repr(float(row[k])) for k in ["xp_radians", "yp_radians", "corrected_latitude", "corrected_longitude", "ascendant", "midheaven"]) + ", " + repr(list(row["cusps"])) + "),\n"
    rust += "];\n"
    (target / "placidus_swiss.inc").write_text(rust)
    print(f"{len(rows)} solved cases, {len(unavailable)} unavailable cases")


if __name__ == "__main__":
    generate()
